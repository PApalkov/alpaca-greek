export type Gender = "m" | "f" | "n";
export type Slot = "nomSg" | "accSg" | "genSg" | "nomPl" | "accPl" | "genPl";

export const SLOTS: Slot[] = ["nomSg", "accSg", "genSg", "nomPl", "accPl", "genPl"];

