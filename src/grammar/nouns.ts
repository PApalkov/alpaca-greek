export const NOUN = new Map(NOUNS.map((x) => [x.key, x]));

export function form(noun: Noun, slot: Slot): string | null {
  return noun.forms[SLOTS.indexOf(slot)];
}

/** τη before most consonants, την before a vowel and κ π τ ξ ψ μπ ντ γκ (also στη/στην). */
export function needsN(word: string): boolean {
  const w = word.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
  return /^([αεηιουω]|κ|π|τ|ξ|ψ|μπ|ντ|γκ)/.test(w);
}

const ARTICLES: Record<Slot, Record<Gender, string>> = {
  nomSg: { m: "ο", f: "η", n: "το" },
  accSg: { m: "τον", f: "τη", n: "το" },
  genSg: { m: "του", f: "της", n: "του" },
  nomPl: { m: "οι", f: "οι", n: "τα" },
  accPl: { m: "τους", f: "τις", n: "τα" },
  genPl: { m: "των", f: "των", n: "των" },
};

export function article(g: Gender, slot: Slot, word: string): string {
  const a = ARTICLES[slot][g];
  return a === "τη" && needsN(word) ? "την" : a;
}

/** Form with its article, e.g. "τους ανθρώπους"; null if the form is not in the table. */
export function withArticle(noun: Noun, slot: Slot): string | null {
  const f = form(noun, slot);
  return f && `${article(noun.g, slot, f)} ${f}`;
}

/** σε merged with the accusative article: στον φίλο, στη Λάρνακα, στους φίλους. */
export function withSe(noun: Noun, slot: "accSg" | "accPl"): string | null {
  const a = withArticle(noun, slot);
  return a && "σ" + a;
}

export function hasPlural(noun: Noun): boolean {
  return form(noun, "nomPl") !== null;
}
