export interface Blank {
  noun: string;
  slot: Slot;
  se: boolean;
}

export const BLANK = /\{(σε\+)?([^:}]+):(\w+)\}/g;

export function blanks(sentence: Sentence): Blank[] {
  return [...sentence.el.matchAll(BLANK)].map((m) => ({ se: !!m[1], noun: m[2], slot: m[3] as Slot }));
}
