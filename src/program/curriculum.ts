import type { EpochPlan, LessonPlan, LessonType } from "./types";

/**
 * The road to a real A2 (the Ελληνομάθεια A2 exam of the Centre for the Greek Language):
 * 8 epochs × 20 lessons, one lesson a day of ~35–45 minutes.
 *
 * Rhythm of an epoch: four units of five lessons — three `core` lessons (new words + one grammar
 * point), one `practice` lesson (no new grammar: long texts, listening, translation, harder tasks),
 * one `task` lesson (an essay and a role-play, both reviewed by AI). The last lesson is a `test`.
 *
 * Time: ~160 lessons × 40 min ≈ 105 h, plus daily warm-ups (~25 h), essays and role-plays with AI
 * (~20 h) ≈ 150 h; with classes and homework this is what A2 usually takes.
 *
 * Grammar order follows the homework (Klik A1): article → nominative/accusative → genitive → verbs.
 * Epochs are written one session at a time with docs/LESSON_PROMPT.md. Lesson entries may be refined
 * when an epoch is written; written lessons must stay in place (progress is stored by position).
 */

const l = (type: LessonType, title: string, theme: string, grammar: string, can: string): LessonPlan => ({ type, title, theme, grammar, can });
const core = (title: string, theme: string, grammar: string, can: string) => l("core", title, theme, grammar, can);
const practice = (title: string, theme: string, grammar: string, can: string) => l("practice", title, theme, grammar, can);
const task = (title: string, theme: string, grammar: string, can: string) => l("task", title, theme, grammar, can);
const test = (title: string, theme: string, grammar: string, can: string) => l("test", title, theme, grammar, can);

